def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def run(*a, **k):
    return subprocess.run(a, check=True, text=True, capture_output=True, **k).stdout.strip()


def maven_entries(pkg):
    lock = json.loads((pkg / 'source-lock.json').read_text())
    out = []
    for e in lock['added_files']:
        rel = e['replacement']
        assert rel.startswith('files/m2/repository/'), rel
        assert e['source'] == 'https://repo.maven.apache.org/maven2/' + rel[len('files/m2/repository/'):], e
        out.append((e['source'], rel, e['sha256']))
    return out


def json_field(obj, dotted):
    for k in dotted.split('.'):
        obj = obj[k]
    return obj


def extract(name, s, tmp):
    """Return {(role, image_path): local_copy} for every base/orig/check entry."""
    need = {}
    for role, path, _ in s['base'] + s['orig']:
        need.setdefault(role, set()).add(path)
    for role, path in s['check']:
        need.setdefault(role, set()).add(path)
    got = {}
    for role, paths in need.items():
        ref = s['images'][role]
        if subprocess.run(['docker', 'image', 'inspect', ref], capture_output=True).returncode:
            raise SystemExit(f'{name}: image {ref} not present locally; pull it first')
        cid = run('docker', 'create', '--platform', 'linux/amd64', ref, 'true')
        try:
            for i, path in enumerate(sorted(paths)):
                dst = tmp / f'{role}-{i}'
                run('docker', 'cp', '-L', f'{cid}:{path}', str(dst))
                got[(role, path)] = dst
        finally:
            run('docker', 'rm', '-f', cid)
    return got


def taskjson_text(rel, field):
    p = ROOT / rel
    if field is None:
        return p.read_bytes()
    return json_field(json.loads(p.read_text()), field).encode()


def split_old_taskjson(text):
    """Return the task-JSON sections of an existing repair.patch (kept verbatim)."""
    lines = text.splitlines(keepends=True)
    sections, cur, keep = [], [], False
    for ln in lines:
        start = ln.startswith('diff ') or (ln.startswith('--- ') and not (cur and cur[-1].startswith('diff ')))
        if start:
            if cur and keep:
                sections.append(''.join(cur))
            cur, keep = [], False
        cur.append(ln)
        if ln.startswith('+++ ') and 'task.json' in ln:
            keep = True
    if cur and keep:
        sections.append(''.join(cur))
    return ''.join(sections)


TEMPLATE = Path(__file__).with_name('materialize.sh.in')


def bash_array(name, rows):
    body = ''.join(f"  {json.dumps('|'.join(r))}\n" for r in rows)
    return f'{name}=(\n{body})\n'


def generate(name):
    s = SPEC[name]
    pkg = REPAIRS / name
    old_patch = (pkg / 'repair.patch').read_text()
    tj_old = split_old_taskjson(old_patch)
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        got = extract(name, s, tmp)
        inputs, outputs = [], {}
        hunks = []
        bases = [(r, p, d, got[(r, p)]) for r, p, d in s['base']]
        for rel, field, d in s['taskjson']:
            b = tmp / ('tj-' + d.replace('/', '_'))
            b.write_bytes(taskjson_text(rel, field))
            bases.append(('taskjson', f'{rel}' + (f'#{field}' if field else ''), d, b))
        for role, path, d, b in bases:
            inputs.append({'source': role, 'path': path, 'sha256': sha(b)})
            if not d.startswith('files/'):
                continue
            new = pkg / d
            assert new.is_file(), f'{name}: reference {d} missing'
            # bytes, not text: keeps CRLF line endings exact
            res = subprocess.run(['diff', '-u', '--label', 'a/' + d, '--label', 'b/' + d, str(b), str(new)],
                                 capture_output=True)
            assert res.returncode in (0, 1), res.stderr
            if res.returncode == 1:
                hunks.append(f'# {d} <- {role}:{path}\n'.encode() + res.stdout)
        for role, path in s['check']:
            inputs.append({'source': role, 'path': path, 'sha256': sha(got[(role, path)]), 'check_only': True})
        for role, path, d in s['orig']:
            assert sha(got[(role, path)]) == sha(pkg / d), f'{name}: {d} differs from image {path}'
        for rel, field, d in s['taskjson']:
            if d.startswith('orig/'):
                assert taskjson_text(rel, field) == (pkg / d).read_bytes(), f'{name}: {d} differs from task JSON'
        dsts = [d for _, _, d in s['base']] + [d for _, _, d in s['orig']] + [d for *_, d in s['taskjson']] \
            + [d for _, d in s['copies']]
        mav = maven_entries(pkg) if s['maven'] else []
        dsts += [d for _, d, _ in mav]
        for d in sorted(set(dsts)):
            outputs[d] = sha(pkg / d)
        for url, d, h in mav:
            assert outputs[d] == h, f'{name}: {d} sha differs from lock'

    header = (f'# repair.patch for {name}: unified diff (diff -u) from the ORIGINAL file to the v2 file.\n'
              f'# Generated by tools/make_materialize.py; apply with `patch -p1` in the\n'
              f'# package directory after materialize.sh has placed the originals (see the `# <dst> <- <source>`\n'
              f'# line above each file).\n')
    if not hunks:
        header += '# No image file changes in this package.\n'
    (pkg / 'repair.patch').write_bytes(header.encode() + b''.join(hunks))
    if tj_old:
        (pkg / 'task-json.diff').write_text(
            '# Task JSON change (tasks/<id>.json -> task.json.in), moved verbatim from the earlier repair.patch.\n'
            + tj_old)

    images = sorted(s['images'].items())
    script = TEMPLATE.read_text()
    data = (f'PKG_NAME={json.dumps(name)}\n'
            + bash_array('IMAGES', images)
            + bash_array('BASE', [(r, p, d) for r, p, d in s['base']])
            + bash_array('ORIG', [(r, p, d) for r, p, d in s['orig']])
            + bash_array('TASKJSON', [(rel, field or '', d) for rel, field, d in s['taskjson']])
            + bash_array('CHECK', [(r, p) for r, p in s['check']])
            + bash_array('COPIES', list(s['copies']))
            + bash_array('MAVEN', [(u, d) for u, d, _ in mav])
            + f'LEAN_BUILD={1 if s["lean"] else 0}\n')
    script = script.replace('@@DATA@@\n', data)
    (pkg / 'materialize.sh').write_text(script)
    os.chmod(pkg / 'materialize.sh', 0o755)

    lock_p = pkg / 'source-lock.json'
    lock = json.loads(lock_p.read_text())
    block = {
        'schema': 'edgebenchverified-materialize-v1',
        'policy': 'Image-derived files are not stored in Git. materialize.sh pulls the pinned images, '
                  'extracts the inputs, applies repair.patch and verifies every output below.',
        'images': dict(images),
        'inputs': inputs,
        'outputs': outputs,
        'repair_patch_sha256': sha(pkg / 'repair.patch'),
        'materialize_sh_sha256': sha(pkg / 'materialize.sh'),
    }
    if (pkg / 'task-json.diff').exists():
        block['task_json_diff_sha256'] = sha(pkg / 'task-json.diff')
    if s['note']:
        block['note'] = s['note']
    if s['lean']:
        block['lean_build'] = lean_block(pkg)
    if 'repair_patch_sha256' in lock:
        lock['repair_patch_sha256'] = block['repair_patch_sha256']
    if isinstance(lock.get('replacement'), dict) and 'repair.patch' in lock['replacement']:
        lock['replacement']['repair.patch'] = block['repair_patch_sha256']
    lock['materialize'] = block
    lock_p.write_text(json.dumps(lock, indent=1, ensure_ascii=False) + '\n')
    print(f'{name}: {len(hunks)} patched file(s), {len(outputs)} verified output(s)')


def lean_block(pkg):
    lock = json.loads((pkg / 'source-lock.json').read_text())
    members = sorted(m.lstrip('/') for m in lock['artifact_tar_members'])
    return {
        'artifact': 'files/judge/v2-build-artifacts.tar',
        'artifact_member_count': len(members),
        'artifact_members': members,
        'expected_listing': 'paired/out/v2-listing.txt',
        'expected_listing_sha256': sha(pkg / 'paired/out/v2-listing.txt'),
        'saved_reference_tar_sha256': lock['replacement_files'].get('files/judge/v2-build-artifacts.tar'),
        'acceptance': 'The tar is rebuilt with `lake build ListDeclAxiom` + `lake build` inside the original '
                      'judge image (offline, --memory 4g). Byte-identical oleans are not required: the '
                      'member set must equal artifact_members and the regenerated ListDeclAxiom listing '
                      'must equal expected_listing byte for byte.',
    }


if __name__ == '__main__':
    names = sys.argv[1:] or sorted(SPEC)
    for n in names:
        generate(n)
