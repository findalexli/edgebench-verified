"""Generate repair.patch, task-json.diff, materialize.sh and the source-lock `materialize`
block for every repairs/*-v2 package.

Policy: repair packages in Git carry only our diffs. Files taken from the EdgeBench images are
regenerated by `materialize.sh` (pull pinned image by digest, `docker create` + `docker cp`,
apply repair.patch, verify sha256 against source-lock.json).

Maintainer use (needs the local reference files/ and orig/ trees and Docker):
  python3 tools/make_materialize.py [package ...]
It extracts the originals from the pinned images, regenerates repair.patch with `diff -u`
(original -> files/), writes materialize.sh and records every output sha256 from the current
reference tree. It never deletes files/ or orig/.
"""
