#!/usr/bin/env python3
"""Extract (K+1)-clique certificates for the official vibrating_path_graph_coloring cases and
emit them as Lean data; also re-check that every certificate pair is an edge of the case file.

K=1: the first edge (K2). K=2: the first triangle found (K3). N=1000, K in {3,4}: the K4/K5 found
by evidence/scripts/vibrating_path_graph_coloring/zero_hit_reachability.py (re-searched here).
Each certificate pair is listed with its 0-based index in the case's edge list.
Usage: vibrating_certs.py CASES_DIR OUT_LEAN"""
import sys, os, hashlib, itertools

def load(p):
    d = open(p).read().split()
    N, M, K = int(d[0]), int(d[1]), int(d[2])
    off = 3 + N
    E = [(int(d[off+3*i]), int(d[off+3*i+1])) for i in range(M)]
    return N, M, K, E

def clique(adj, size, N):
    order = sorted(range(1, N+1), key=lambda x: -len(adj[x]))
    def ext(cl, cand):
        if len(cl) == size: return cl
        for v in sorted(cand):
            r = ext(cl+[v], cand & adj[v])
            if r: return r
        return None
    for v in order:
        r = ext([v], set(w for w in adj[v] if w > v))
        if r: return r
    return None

def main(cd, out):
    rows = []; agg = hashlib.sha256()
    for f in sorted(os.listdir(cd)):
        raw = open(os.path.join(cd, f), 'rb').read(); h = hashlib.sha256(raw).hexdigest()
        agg.update(f.encode() + b' ' + h.encode() + b'\n')
        N, M, K, E = load(os.path.join(cd, f))
        idx = {}
        for i, (u, v) in enumerate(E): idx.setdefault((u, v), i)
        adj = {v: set() for v in range(1, N+1)}
        for u, v in E: adj[u].add(v); adj[v].add(u)
        cl = None
        if K == 1: cl = list(E[0])
        elif K == 2:
            for u, v in E:
                w = adj[u] & adj[v]
                if w: cl = [u, v, min(w)]; break
        elif N <= 1000: cl = clique(adj, K+1, N)
        if cl is None:
            print(f"{f} N={N} K={K} sha256={h} NO_CERT"); continue
        pairs = []
        for a, b in itertools.combinations(cl, 2):
            if (a, b) in idx: pairs.append((a, b, idx[(a, b)]))
            elif (b, a) in idx: pairs.append((b, a, idx[(b, a)]))
            else: raise SystemExit(f"{f}: pair {a},{b} not an edge")
        # independent re-check from the raw file tokens
        d = raw.decode().split(); off = 3 + N
        for a, b, i in pairs:
            assert (int(d[off+3*i]), int(d[off+3*i+1])) == (a, b)
        rows.append((f, h, N, K, cl, pairs))
        print(f"{f} N={N} K={K} sha256={h} K{K+1}={cl} edge_idx={[p[2] for p in pairs]}")
    print(f"CERTIFIED {len(rows)} aggregate_sha256(name sha lines)={agg.hexdigest()}")
    with open(out, 'w') as o:
        o.write("-- Generated by evidence/formal/scripts/vibrating_certs.py; do not edit.\n")
        o.write("-- Each entry: case, N, K, clique vertices (1-indexed), pairs as they appear in the edge list.\n")
        o.write("-- Case-file sha256 and edge-list indices: see vibrating_certs.out.\n")
        o.write("namespace Ebv.Vibrating\n\ndef certs : List Cert := [\n")
        o.write(",\n".join(f"  ⟨\"{f}\", {N}, {K}, {cl}, {[(a, b) for a, b, _ in p]}⟩"
                           for f, h, N, K, cl, p in rows))
        o.write("\n]\n\nend Ebv.Vibrating\n")

if __name__ == '__main__': main(sys.argv[1], sys.argv[2])
