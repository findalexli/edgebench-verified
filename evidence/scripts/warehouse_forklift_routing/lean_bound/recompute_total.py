#!/usr/bin/env python3
"""Independent exact recomputation of the TOTAL lower bound on the 50 judge inputs, parsing
each input line-by-line exactly as tools/bin/tester does, checking the Lean theorem's
hypotheses per case, emitting a Lean file that re-checks the arithmetic in the kernel, and
mapping the bound through the harness rescale.
Usage: recompute_total.py <cases_dir> <task_json> <lean_out>"""
import sys, os, glob, json, math
from fractions import Fraction as F
from decimal import Decimal, ROUND_FLOOR

cases_dir, task_json, lean_out = sys.argv[1:4]
files = sorted(glob.glob(os.path.join(cases_dir, '*.txt')))
assert len(files) == 50, len(files)
L = lambda R, C: 2 * R * C * (R + C - 1) - 6 * (R + C - 2) - 2
case_score_lb = lambda R, C: F(L(R, C) + 2, R + C - 1) - 2 * R * C + 20   # = 20 - 6(R+C-2)/(R+C-1)
total = F(0); total_disp_lb = F(0); dims_all = []; hyp_fail = 0
for f in files:
    lines = open(f).read().strip().split('\n')
    T = int(lines[0]); li = 1; per = []; dims = []
    for _ in range(T):
        R, C = map(int, lines[li].split()); li += 1
        ship = list(map(int, lines[li].split())); li += 1
        n = R * C - 1
        ok = (R >= 1 and C >= 1 and R * C >= 2 and len(ship) == n and sorted(ship) == list(range(1, n + 1))
              and ship[n - 1] != 1)
        hyp_fail += not ok
        assert case_score_lb(R, C) == 20 - F(6 * (R + C - 2), R + C - 1)
        per.append(case_score_lb(R, C)); dims.append((R, C))
    assert li == len(lines)
    avg = sum(per) / T
    total += avg
    # tester prints f"{avg:.1f}"; displayed value >= floor(10*avg)/10 (rounding is monotone and
    # never goes below the floor at 1 dp; float error of the tester's avg is < 1e-9 here)
    total_disp_lb += F(math.floor(avg * 10 - F(1, 10**6)), 10)
    dims_all.append(dims)
print("files", len(files), "| cases", sum(len(d) for d in dims_all), "| cases failing Lean hypotheses", hyp_fail)
print("exact TOTAL lower bound:", total, "=", "%.6f" % float(total))
print("lower bound on TOTAL_SCORE as actually summed from 1-dp displayed values:", float(total_disp_lb))
sys.path.insert(0, '/home/alex/edgebench-verified')
from sforge.harness.score_rescale import parse_rescale_spec, rescale_score
spec_d = json.load(open(task_json))['judge']['rescale']; spec = parse_rescale_spec(spec_d)
print("rescale spec", spec_d)
for raw in [float(total), float(total_disp_lb), 1000.0, spec_d['rank30'], spec_d['rank1'], spec_d['super_anchor']]:
    print("  rescale(%.4f) = %.4f" % (raw, rescale_score(spec, raw)))
# monotonicity spot check of the rescale on [lb, baseline]
xs = [float(total_disp_lb) + i * 0.5 for i in range(0, 46000)]
vals = [rescale_score(spec, x) for x in xs]
print("rescale non-increasing on grid from lb to ~23k:", all(a >= b for a, b in zip(vals, vals[1:])),
      "| max over grid", max(vals))
# Lean arithmetic file
with open(lean_out, 'w') as o:
    o.write("/- Generated by scripts/warehouse_forklift_routing/lean_bound/recompute_total.py from the 50 judge inputs.\n"
            "   (R,C) for each of the 5 cases of each input file, in file order 0000..0049. -/\n")
    o.write("import Mathlib.Tactic\n\nnamespace EbvWarehouseData\n\n")
    o.write("def dims : List (List (ℕ × ℕ)) := [\n")
    o.write(",\n".join("  [" + ", ".join("(%d, %d)" % rc for rc in d) + "]" for d in dims_all))
    o.write("]\n\n")
    o.write("/-- per-case lower bound on the score from `EbvWarehouse.score_bound` -/\n")
    o.write("def caseLB (rc : ℕ × ℕ) : ℚ := 20 - 6 * ((rc.1 : ℚ) + rc.2 - 2) / ((rc.1 : ℚ) + rc.2 - 1)\n\n")
    o.write("def totalLB : ℚ := (dims.map (fun d => (d.map caseLB).sum / (d.length : ℚ))).sum\n\n")
    o.write("theorem dims_shape : dims.length = 50 ∧ dims.all (fun d => d.length = 5) := by decide\n\n")
    o.write("theorem totalLB_eq : totalLB = (%d : ℚ) / %d := by\n  simp only [totalLB, dims]; norm_num [caseLB]\n\n" % (total.numerator, total.denominator))
    o.write("theorem totalLB_gt : (712.53 : ℚ) < totalLB := by rw [totalLB_eq]; norm_num\n\n")
    o.write("/-- even after losing 0.05 per input to 1-dp display rounding, the bound exceeds rank1 (and super_anchor) -/\n")
    o.write("theorem displayed_gt_rank1 : (395.802847 : ℚ) < totalLB - 50 * (1/20) := by\n  rw [totalLB_eq]; norm_num\n\n")
    o.write("end EbvWarehouseData\n\n")
    for th in ("dims_shape", "totalLB_eq", "totalLB_gt", "displayed_gt_rank1"):
        o.write("#print axioms EbvWarehouseData.%s\n" % th)
print("wrote", lean_out)
